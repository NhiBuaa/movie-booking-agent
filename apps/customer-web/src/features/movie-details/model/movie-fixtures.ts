export function filterShowtimes(
  daySchedule: DaySchedule,
  format: 'ALL' | '2D' | 'IMAX'
): DaySchedule {
  if (format === 'ALL') {
    return daySchedule;
  }

  const filteredCinemas = daySchedule.cinemas
    .map((cinema) => ({
      ...cinema,
      slots: cinema.slots.filter((slot) => slot.format === format),
    }))
    .filter((cinema) => cinema.slots.length > 0);

  return {
    ...daySchedule,
    cinemas: filteredCinemas,
  };
}
